async function createUser(page, name) {
  page.on('pageerror', (error) => errors.push(error.message))
  await page.route('**/*', async (route) => {
    const req = route.request()
    if (['POST', 'PATCH', 'DELETE'].includes(req.method()) && !req.url().startsWith('http://127.0.0.1:18016/')) {
      await route.abort(); throw new Error('QA write blocked: only isolated API :18016 allowed')
    }
    await route.continue()
  })
  await page.goto(UI_URL)
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await page.getByLabel('Full name', { exact: true }).fill(name)
  await page.getByLabel('Email address').fill(`${name.toLowerCase().replaceAll(' ', '-')}-${Date.now()}@example.com`)
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByLabel('Confirm password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Create your account', exact: true }).click()
  await text(page, 'Account created. Sign in to continue.')
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Sign in to PayFlow' }).click()
  await configurePin(page, password)
  await page.getByLabel('Demo bank').selectOption('Grove Demo Bank')
  await page.getByRole('button', { name: 'Create demo account', exact: true }).click()
  await page.getByRole('article', { name: 'Simulated bank account' }).waitFor()
  return page.locator('.account-details dd').last().textContent()
}
